# tables
# ----------------------------------------------------------------------
def table(rows, methods):
    out = {}
    for sid in SCENARIOS:
        for m in methods:
            rs = [r for r in rows if r["scenario"] == sid and r["method"] == m]
            for k, _, _ in METRICS:
                out[(sid, m, k)] = mean_ci([r[k] for r in rs])
    return out


def ranking(tab, methods):
    """Rank by PDR; ties (within 0.001) broken by worst-user goodput, then latency."""
    res = {}
    for sid in SCENARIOS:
        key = lambda m: (round(tab[(sid, m, "pdr")][0], 3), tab[(sid, m, "min_user_tput_mbps")][0],
                         -tab[(sid, m, "mean_latency_ms")][0])
        res[sid] = sorted(methods, key=key, reverse=True)
    return res


def write_tables(out: Path, tab, methods, rank, summary, candidate):
    with open(out / "metrics_by_method.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "method", "family", "metric", "mean", "ci95_half_width", "n_seeds"])
        for (sid, m, k), (mu, ci, n) in tab.items():
            w.writerow([sid, m, FAMILY.get(m, ""), k, f"{mu:.6g}", f"{ci:.6g}", n])

    L = ["# Tables (generated by ml/analyze_closed_loop.py)", "",
         "Mean ± 95% CI half-width over seeds (t-interval). Methods ranked by packet delivery ratio "
         "(ties within 0.001 broken by worst-user goodput, then mean latency).", ""]
    for sid in SCENARIOS:
        L += [f"## {sid}", "", "| rank | method | " + " | ".join(lbl for _, lbl, _ in METRICS) + " |",
              "|---|---|" + "---|" * len(METRICS)]
        for i, m in enumerate(rank[sid], 1):
            cells = []
            for k, _, _ in METRICS:
                mu, ci, _ = tab[(sid, m, k)]
                d = 1 if k in ("loss_pct", "mean_latency_ms", "p95_flow_latency_ms", "movement_m") else 3
                cells.append(f"{mu:.{d}f} ± {ci:.{d}f}")
            L.append(f"| {i} | {m} | " + " | ".join(cells) + " |")
        L += ["", f"Paired per-seed difference in PDR, **{candidate}** − baseline "
              "(mean, bootstrap 95% CI, wins/ties/losses, Wilcoxon p, uncorrected unless noted):", "",
              "| baseline | ΔPDR | 95% CI | W/T/L | p |", "|---|---|---|---|---|"]
        for pair, st in summary[sid]["paired"].items():
            q = st["pdr"]
            holm = f" (Holm {q['holm_p']:.2g})" if "holm_p" in q else ""
            L.append(f"| {pair.split('_vs_')[1]} | {q['mean_diff']:+.4f} | [{q['ci95'][0]:+.4f}, "
                     f"{q['ci95'][1]:+.4f}] | {q['wins']}/{q['ties']}/{q['losses']} | "
                     f"{q['wilcoxon_p']:.2g}{holm} |")
        L.append("")
    (out / "tables.md").write_text("\n".join(L))


