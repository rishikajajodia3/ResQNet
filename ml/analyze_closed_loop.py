def _style(ax):
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color(INK2)
    ax.tick_params(colors=INK2, labelsize=9, length=0)


def _legend(fig, methods):
    from matplotlib.lines import Line2D
    fams = list(dict.fromkeys(FAMILY.get(m, "baseline") for m in methods))
    fig.legend([Line2D([], [], marker="o", ls="", color=COLOURS[f], markersize=7) for f in fams], fams,
               loc="lower center", ncol=len(fams), frameon=False, fontsize=9, labelcolor=INK2)


def dot_figure(path, tab, methods, metrics, title):
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(len(metrics), len(SCENARIOS), figsize=(13, 0.42 * len(methods) * len(metrics) + 1.6),
                             squeeze=False)
    y = np.arange(len(methods))[::-1]
    for r, (k, label, hb) in enumerate(metrics):
        for c, sid in enumerate(SCENARIOS):
            ax = axes[r, c]
            _style(ax)
            for yi, m in zip(y, methods):
                mu, ci, _ = tab[(sid, m, k)]
                col = COLOURS[FAMILY.get(m, "baseline")]
                ax.errorbar(mu, yi, xerr=ci, fmt="o", color=col, ecolor=col, elinewidth=2, capsize=0,
                            markersize=8, markeredgecolor="white", markeredgewidth=1.5)
            # do not magnify noise: a near-flat panel gets a range of +-2 % around its centre
            vals = [tab[(sid, m, k)][0] for m in methods]
            centre, span = (max(vals) + min(vals)) / 2, max(vals) - min(vals)
            if k != "movement_m" and span < 0.02 * max(abs(centre), 1e-9):
                half = max(0.02 * abs(centre), 1e-3)
                ax.set_xlim(centre - half, centre + half)
                ax.text(0.5, 0.5, "all methods within 2 % —\nno practical difference", transform=ax.transAxes,
                        ha="center", va="center", fontsize=9, color=INK2,
                        bbox=dict(facecolor="white", edgecolor=GRID, boxstyle="round,pad=0.4"))
            ax.set_yticks(y)
            ax.set_yticklabels(methods if c == 0 else [], color=INK)
            ax.set_title(f"{sid} — {label}", fontsize=10, color=INK, loc="left")
            ax.set_xlabel(("higher is better" if hb else "lower is better"), fontsize=8, color=INK2)
    fig.suptitle(title, fontsize=13, color=INK, x=0.01, ha="left")
    _legend(fig, methods)
    fig.tight_layout(rect=(0, 0.04, 1, 0.97))
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)


def paired_figure(path, summary, candidate, methods):
    import matplotlib.pyplot as plt
    bases = [m for m in methods if m != candidate]
    from matplotlib.ticker import MaxNLocator
    fig, axes = plt.subplots(1, len(SCENARIOS), figsize=(15, 0.5 * len(bases) + 1.8))
    y = np.arange(len(bases))[::-1]
    for ax, sid in zip(axes, SCENARIOS):
        _style(ax)
        ax.axvline(0, color=INK2, linewidth=1)
        labels = []
        for yi, b in zip(y, bases):
            q = summary[sid]["paired"][f"{candidate}_vs_{b}"]["pdr"]
            lo, hi = q["ci95"]
            col = COLOURS[FAMILY.get(b, "baseline")]
            ax.plot([lo, hi], [yi, yi], color=col, linewidth=2)
            ax.plot(q["mean_diff"], yi, "o", color=col, markersize=8, markeredgecolor="white", markeredgewidth=1.5)
            labels.append(f"{b}\n{q['wins']}/{q['ties']}/{q['losses']}, p={q['wilcoxon_p']:.2g}")
        ax.set_yticks(y)
        ax.set_yticklabels(labels, color=INK, fontsize=8)
        ax.xaxis.set_major_locator(MaxNLocator(4))
        ax.set_title(sid, fontsize=10, color=INK, loc="left")
        ax.set_xlabel(f"Δ PDR ({candidate} − baseline), 95% bootstrap CI", fontsize=8, color=INK2)
    fig.suptitle(f"Paired per-seed PDR difference: {candidate} vs every other method "
                 "(right of 0 = ns3_refine better; W/T/L over 20 seeds)", fontsize=12, color=INK, x=0.01, ha="left")
    _legend(fig, bases)
    fig.tight_layout(rect=(0, 0.05, 1, 0.95))
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)


def refine_figure(path, exp: Path):
    """Search PDR (3 s, RngRun 101) at each stage of ns3_refine, per instance."""
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, len(SCENARIOS), figsize=(13, 3.8), sharey=False)
    stages = ["best start", "after 20 m round", "after 10 m round"]
    for ax, sid in zip(axes, SCENARIOS):
        _style(ax)
        ax.grid(axis="y", color=GRID, linewidth=0.8)
        traces = []
        for f in sorted((exp / "refine").glob(f"{sid}_s*.json")):
            if not f.stem.split("_s")[-1].isdigit():
                continue
            h = json.loads(f.read_text())["history"]
            v = [h[0][1]]
            v.append(next((x for n, x in h if n == "move 20 m"), v[-1]))
            v.append(next((x for n, x in h if n == "move 10 m"), v[-1]))
            traces.append(v)
            ax.plot(range(3), v, color="#b8b7b1", linewidth=1)
        t = np.array(traces)
        ax.plot(range(3), t.mean(0), color=COLOURS["ns-3 in the loop"], linewidth=2.5, marker="o", markersize=8)
        ax.set_xticks(range(3))
        ax.set_xticklabels(stages, fontsize=8)
        ax.set_title(f"{sid} (n={len(t)}): mean {t[:, 0].mean():.3f} → {t[:, 2].mean():.3f}",
                     fontsize=10, color=INK, loc="left")
        ax.set_ylabel("measured search PDR", fontsize=8, color=INK2)
    fig.suptitle("ns3_refine feedback loop: each round keeps a move only if ns-3 measured a gain "
                 "(grey = one seed, orange = mean)", fontsize=12, color=INK, x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)


