def audit(exp: Path, rows) -> dict:
    from scipy import stats
    import evaluate_closed_loop as ecl
    import checkpoint as ck
    import placement_search as ps
    ecl.register_eval_scenarios()
    cfg = json.loads((exp / "config.json").read_text())
    runner = ck.CachedNs3Runner(exp / "ns3_runs", cfg["files"]["ns3/binary"], run_fn=None, log=lambda m: None)
    pl = {(p["scenario"], p["seed"]): p for p in
          (json.loads(f.read_text()) for f in (exp / "placements").glob("*.json"))}
    search_args = (f"--RngRun={ps.SEARCH_RNG_RUN}", f"--trafficSeconds={ps.SEARCH_TRAFFIC_SECONDS}")
    final_args = [(f"--RngRun={rr}",) for rr in cfg["settings"]["final_rng_runs"]]

    A = {"rows": len(rows), "rederived": 0, "mismatches": [], "missing_final_runs": 0,
         "packets_sent_per_user": set(), "altitudes_m": collections.defaultdict(set),
         "search_vs_final": {}}
    sv = collections.defaultdict(lambda: ([], []))
    for r in rows:
        sid = r["scenario"]
        for p in r["uav_positions"]:
            A["altitudes_m"][sid].add(p[2])
        x = pl[(sid, r["seed"])]
        _, h = ecl.handoff_for(r["uav_positions"], x["users"], sid, r["seed"], cfg["settings"]["rf_mode"])
        res = [runner.cached(h, a) for a in final_args]
        if any(c is None for c in res):
            A["missing_final_runs"] += sum(c is None for c in res)
            continue
        A["packets_sent_per_user"].update(int(s) for c in res for s in c["per_user_sent"])
        s = ecl.score(res)
        A["rederived"] += 1
        for k in ("pdr", "mean_user_tput_mbps", "min_user_tput_mbps", "jain_fairness", "users_pdr_ge_90",
                  "mean_latency_ms", "p95_flow_latency_ms"):
            if s[k] is not None and r[k] is not None and abs(s[k] - r[k]) > 1e-9:
                A["mismatches"].append([sid, r["seed"], r["method"], k])
        c = runner.cached(h, search_args)
        if c is not None:
            sv[sid][0].append(c["pdr"]); sv[sid][1].append(r["pdr"])
    for sid, (a, b) in sv.items():
        A["search_vs_final"][sid] = {
            "n": len(a), "spearman": float(stats.spearmanr(a, b).statistic) if len(set(a)) > 1 else None,
            "mean_abs_diff": float(np.mean(np.abs(np.array(a) - b)))}
    A["packets_sent_per_user"] = sorted(A["packets_sent_per_user"])
    A["altitudes_m"] = {k: sorted(v) for k, v in A["altitudes_m"].items()}

    refine = {}
    for sid in SCENARIOS:
        moves = collections.Counter(); runs = []; still = 0
        for f in sorted((exp / "refine").glob(f"{sid}_s*.json")):
            if not f.stem.split("_s")[-1].isdigit():
                continue
            d = json.loads(f.read_text())
            moves[len(d["history"]) - 1] += 1
            runs.append(d["runs"])
            still += any(n == "move 10 m" for n, _ in d["history"])
        refine[sid] = {"accepted_moves_histogram": dict(sorted(moves.items())),
                       "ns3_search_runs_per_instance": float(np.mean(runs)) if runs else None,
                       "improved_in_last_round": still}
    A["ns3_refine"] = refine
    return A


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exp", default=str(_ROOT / "data" / "experiments_closed_loop" / "main_surrogate"))
    ap.add_argument("--out", default=str(_ROOT / "data" / "experiments_closed_loop" / "analysis_report"))
    ap.add_argument("--no-audit", action="store_true", help="skip re-deriving scores from the ns-3 cache")
    args = ap.parse_args()
    exp, out = Path(args.exp).resolve(), Path(args.out).resolve()
    if out == exp or exp in out.parents:
        raise SystemExit("--out must be outside the experiment directory")
    out.mkdir(parents=True, exist_ok=True)

    import matplotlib
    matplotlib.use("Agg")
    rows = json.loads((exp / "rows.json").read_text())["rows"]
    sj = json.loads((exp / "summary.json").read_text())
    meta, summary = sj["meta"], sj["summary"]
    methods, candidate = meta["methods"], meta["candidate"]

    tab = table(rows, methods)
    rank = ranking(tab, methods)
    write_tables(out, tab, methods, rank, summary, candidate)
    dot_figure(out / "fig1_delivery.png", tab, methods, METRICS[:2], "Packet delivery and loss (final ns-3 scoring, mean ± 95% CI over 20 seeds)")
    dot_figure(out / "fig2_latency.png", tab, methods, METRICS[2:4], "Latency of delivered packets (mean ± 95% CI over 20 seeds)")
    dot_figure(out / "fig3_goodput_fairness.png", tab, methods, METRICS[4:7], "Goodput and fairness (mean ± 95% CI over 20 seeds)")
    dot_figure(out / "fig4_movement.png", tab, methods, METRICS[7:], "UAV movement from the fixed layout (mean ± 95% CI over 20 seeds)")
    paired_figure(out / "fig5_paired_pdr.png", summary, candidate, methods)
    refine_figure(out / "fig6_refine_trace.png", exp)

    result = {"experiment": str(exp), "meta": meta, "ranking_by_pdr": rank,
              "strongest_competitor": {sid: next(m for m in rank[sid] if m != candidate) for sid in SCENARIOS}}
    if not args.no_audit:
        result["audit"] = audit(exp, rows)
    (out / "audit.json").write_text(json.dumps(result, indent=1))
    print(json.dumps({k: v for k, v in result.items() if k != "meta"}, indent=1))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
