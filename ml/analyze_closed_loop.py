"""Plots, tables and audit checks for a finished closed-loop experiment.

Reads an evaluate_closed_loop.py output directory (never writes to it) and
writes figures, CSV/Markdown tables and audit.json to a separate directory:

    python ml/analyze_closed_loop.py \
        --exp data/experiments_closed_loop/main_surrogate \
        --out data/experiments_closed_loop/analysis_report

No simulation is run. The audit re-derives every final score from the raw
ns-3 runs cached in <exp>/ns3_runs, so a mismatch between the reported
numbers and the simulator output would show up here.
"""

from __future__ import annotations

import argparse
import collections
import csv
import json
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parent
for p in (_ROOT, _HERE, _ROOT / "sionna"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import numpy as np  # noqa: E402

SCENARIOS = ["wide_area", "blocked_urban", "flood_shelters"]
# method -> family; colour follows the family, so identity is also carried by the axis label
FAMILY = {
    "fixed": "baseline", "random": "baseline",
    "ppo_network": "PPO policy", "ppo_calibrated": "PPO policy", "ppo_calibrated_30": "PPO policy",
    "greedy_joint": "surrogate search", "coordinate": "surrogate search", "evolution": "surrogate search",
    "ns3_refine": "ns-3 in the loop", "ns3_refine_iter": "ns-3 in the loop",
}
COLOURS = {"baseline": "#8a8984", "PPO policy": "#2a78d6",
           "surrogate search": "#1baf7a", "ns-3 in the loop": "#eb6834"}
INK, INK2, GRID = "#0b0b0b", "#52514e", "#e4e3df"

# (key, label, higher_is_better)
METRICS = [
    ("pdr", "Packet delivery ratio", True),
    ("loss_pct", "Packet loss (%)", False),
    ("mean_latency_ms", "Mean latency (ms)", False),
    ("p95_flow_latency_ms", "p95 of per-user mean latency (ms)", False),
    ("mean_user_tput_mbps", "Mean per-user goodput (Mbps)", True),
    ("min_user_tput_mbps", "Worst-user goodput (Mbps)", True),
    ("jain_fairness", "Jain fairness index", True),
    ("movement_m", "Mean UAV movement (m)", False),
]


def mean_ci(vals):
    from scipy import stats
    a = np.asarray([v for v in vals if v is not None], dtype=float)
    if len(a) < 2:
        return float(a.mean()) if len(a) else None, 0.0, len(a)
    return float(a.mean()), float(stats.t.ppf(0.975, len(a) - 1) * a.std(ddof=1) / np.sqrt(len(a))), len(a)


